/**
 * components/emoji-data.ts — emoji 选择面板数据集
 *
 * 内置常用 emoji 分类表(Unicode 字符统一以 \u 码点转义书写,
 * 避免源码文件编码差异导致乱码);分类文案键指向 EditorI18nMessages。
 * 每条 emoji 附带「中文 / 拼音 / 英文」空格分隔关键词,供面板搜索
 * 逐词精准匹配(拼音兼容分写与连写,匹配规则见 emoji-picker)。
 */
import type { EditorI18nMessages } from '../types/editor';

/**
 * 单条 emoji 数据。
 */
export interface EmojiEntry {
  /** emoji 字符。 */
  char: string;
  /** 空格分隔的搜索关键词(中文 / 拼音 / 英文混排)。 */
  keywords: string;
}

/**
 * emoji 分类定义。
 */
export interface EmojiCategory {
  /** 分类文案在 EditorI18nMessages 中的键名。 */
  labelKey: EmojiCategoryLabelKey;
  /** 该分类下的 emoji 列表。 */
  emojis: EmojiEntry[];
}

/** 分类文案键集合(与 EditorI18nMessages 中的 emojiPickerCategory* 键一一对应)。 */
export type EmojiCategoryLabelKey = Extract<keyof EditorI18nMessages, `emojiPickerCategory${string}`>;

/** 数据元组:[emoji 字符, 关键词串],压缩书写用。 */
type EmojiTuple = readonly [string, string];

/** 元组数组 → emoji 条目数组。 */
const toEntries = (tuples: readonly EmojiTuple[]): EmojiEntry[] =>
  tuples.map(([char, keywords]) => ({ char, keywords }));

